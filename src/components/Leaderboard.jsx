import React, { useState, useEffect } from 'react';
import { 
  Trophy, 
  Clock, 
  Target, 
  X, 
  Trash2, 
  Cloud, 
  Database, 
  Check, 
  RefreshCw, 
  ExternalLink,
  Code,
  Copy,
  Crown
} from 'lucide-react';
import { 
  getStoredSupabaseConfig, 
  saveStoredSupabaseConfig, 
  clearStoredSupabaseConfig, 
  isSupabaseActive 
} from '../utils/supabaseClient';

export default function Leaderboard({ 
  isOpen, 
  onClose, 
  leaderboard, 
  onRefresh, 
  onClearLeaderboard 
}) {
  const [showConfig, setShowConfig] = useState(false);
  const [supabaseUrl, setSupabaseUrl] = useState('');
  const [supabaseKey, setSupabaseKey] = useState('');
  const [configSaved, setConfigSaved] = useState(false);
  const [copiedSql, setCopiedSql] = useState(false);
  const [isRefreshing, setIsRefreshing] = useState(false);

  useEffect(() => {
    if (isOpen) {
      const config = getStoredSupabaseConfig();
      setSupabaseUrl(config.url || '');
      setSupabaseKey(config.anonKey || '');
    }
  }, [isOpen]);

  if (!isOpen) return null;

  const isConnected = isSupabaseActive();

  const handleSaveConfig = (e) => {
    e.preventDefault();
    saveStoredSupabaseConfig(supabaseUrl.trim(), supabaseKey.trim());
    setConfigSaved(true);
    setTimeout(() => setConfigSaved(false), 2500);
    if (onRefresh) onRefresh();
  };

  const handleClearConfig = () => {
    clearStoredSupabaseConfig();
    setSupabaseUrl('');
    setSupabaseKey('');
    if (onRefresh) onRefresh();
  };

  const handleRefreshClick = async () => {
    setIsRefreshing(true);
    if (onRefresh) await onRefresh();
    setTimeout(() => setIsRefreshing(false), 600);
  };

  const sqlScript = `-- Crie a tabela no Supabase:
create table public.leaderboard (
  id bigint generated by default as identity primary key,
  name text not null,
  score integer not null,
  accuracy integer not null,
  total_time integer not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.leaderboard enable row level security;
create policy "Permitir leitura pública" on public.leaderboard for select using (true);
create policy "Permitir inserção pública" on public.leaderboard for insert with check (true);`;

  const copySql = () => {
    navigator.clipboard.writeText(sqlScript);
    setCopiedSql(true);
    setTimeout(() => setCopiedSql(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/70 p-4 backdrop-blur-sm animate-fadeIn">
      <div className="relative w-full max-w-xl rounded-3xl border-[3px] border-black bg-[#FDFBF7] p-6 shadow-neo-lg dark:bg-[#1F2024] dark:border-black max-h-[92vh] flex flex-col">
        
        {/* Topo do Placar Arcade */}
        <div className="flex items-start justify-between border-b-2 border-black/10 pb-4 dark:border-white/10">
          <div className="flex items-center gap-3">
            <div className="flex h-12 w-12 items-center justify-center rounded-2xl border-2 border-black bg-[#FFE600] text-black shadow-neo-sm">
              <Crown className="h-6 w-6" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h2 className="font-pixel text-base font-bold text-black dark:text-white uppercase">
                  HIGH SCORES
                </h2>
                {isConnected ? (
                  <span className="inline-flex items-center gap-1 rounded border border-black bg-[#22C55E] px-2 py-0.5 font-pixel text-[8px] font-bold text-white shadow-[1px_1px_0px_#000]">
                    <Cloud className="h-2.5 w-2.5" /> SUPABASE
                  </span>
                ) : (
                  <span className="inline-flex items-center gap-1 rounded border border-black bg-slate-200 px-2 py-0.5 font-pixel text-[8px] font-bold text-black shadow-[1px_1px_0px_#000] dark:bg-slate-700 dark:text-white">
                    <Database className="h-2.5 w-2.5" /> LOCAL
                  </span>
                )}
              </div>
              <p className="text-xs font-semibold text-slate-500 dark:text-slate-400 mt-0.5">
                {isConnected ? "Sincronizado na nuvem (todos os alunos da turma)" : "Salvo localmente no seu navegador"}
              </p>
            </div>
          </div>

          <div className="flex items-center gap-1.5">
            <button
              onClick={handleRefreshClick}
              disabled={isRefreshing}
              className={`neo-btn rounded-lg bg-white p-2 text-black shadow-neo-sm dark:bg-[#121316] dark:text-white ${isRefreshing ? 'animate-spin' : ''}`}
              title="Recarregar Placar"
            >
              <RefreshCw className="h-4 w-4" />
            </button>
            <button
              onClick={onClose}
              className="neo-btn rounded-lg bg-white p-2 text-black shadow-neo-sm dark:bg-[#121316] dark:text-white"
            >
              <X className="h-4 w-4" />
            </button>
          </div>
        </div>

        {/* Botão de Alternância da Configuração */}
        <div className="my-2.5 flex items-center justify-between text-xs">
          <span className="font-pixel text-[10px] text-slate-500">
            {leaderboard.length} JOGADORES NO PLACAR
          </span>
          <button
            onClick={() => setShowConfig(!showConfig)}
            className="flex items-center gap-1 font-pixel text-[10px] text-[#7928CA] dark:text-[#FFE600] underline font-bold hover:opacity-80"
          >
            <Database className="h-3 w-3" />
            <span>{showConfig ? "FECHAR CONEXÃO" : "⚙️ CONECTAR SUPABASE"}</span>
          </button>
        </div>

        {/* Painel Expansível de Configuração */}
        {showConfig && (
          <div className="mb-3 rounded-2xl border-2 border-black bg-white p-4 text-xs shadow-neo-sm dark:bg-[#16161A]">
            <div className="flex items-center justify-between mb-2">
              <h3 className="font-pixel text-[11px] font-bold text-black dark:text-white flex items-center gap-1.5 uppercase">
                <Cloud className="h-4 w-4 text-[#00DFD8]" />
                BANCO DE DADOS SUPABASE
              </h3>
              <a
                href="https://supabase.com"
                target="_blank"
                rel="noreferrer"
                className="font-pixel text-[9px] flex items-center gap-1 text-[#7928CA] dark:text-[#FFE600] hover:underline"
              >
                CRIAR CONTA <ExternalLink className="h-2.5 w-2.5" />
              </a>
            </div>

            <p className="text-slate-600 dark:text-slate-300 mb-3 text-[11px]">
              Insira a <strong>Project URL</strong> e a <strong>anon public key</strong> para conectar o ranking à nuvem:
            </p>

            <form onSubmit={handleSaveConfig} className="space-y-2">
              <div>
                <input
                  type="url"
                  placeholder="https://xyz.supabase.co"
                  value={supabaseUrl}
                  onChange={(e) => setSupabaseUrl(e.target.value)}
                  className="w-full rounded-lg border-2 border-black bg-[#FDFBF7] px-3 py-1.5 font-mono text-xs text-black outline-none shadow-neo-sm dark:bg-[#1F2024] dark:text-white"
                />
              </div>

              <div>
                <input
                  type="password"
                  placeholder="Chave anon/public (eyJhb...)"
                  value={supabaseKey}
                  onChange={(e) => setSupabaseKey(e.target.value)}
                  className="w-full rounded-lg border-2 border-black bg-[#FDFBF7] px-3 py-1.5 font-mono text-xs text-black outline-none shadow-neo-sm dark:bg-[#1F2024] dark:text-white"
                />
              </div>

              <div className="flex items-center gap-2 pt-1">
                <button
                  type="submit"
                  className="neo-btn rounded-lg bg-[#FFE600] px-3 py-1.5 font-pixel text-[10px] font-bold text-black uppercase cursor-pointer"
                >
                  CONECTAR BANCO
                </button>
                {isConnected && (
                  <button
                    type="button"
                    onClick={handleClearConfig}
                    className="neo-btn rounded-lg bg-white px-3 py-1.5 font-pixel text-[10px] font-bold text-black uppercase dark:bg-slate-800 dark:text-white"
                  >
                    DESCONECTAR
                  </button>
                )}
                {configSaved && (
                  <span className="flex items-center gap-1 font-pixel text-[10px] font-bold text-[#22C55E]">
                    <Check className="h-4 w-4" /> CONECTADO!
                  </span>
                )}
              </div>
            </form>

            {/* SQL Snippet */}
            <div className="mt-3 pt-2 border-t border-black/10 dark:border-white/10 flex items-center justify-between">
              <span className="font-pixel text-[9px] text-slate-500 uppercase">
                TABELA: public.leaderboard
              </span>
              <button
                onClick={copySql}
                className="flex items-center gap-1 font-pixel text-[9px] text-[#7928CA] dark:text-[#FFE600] font-bold underline"
              >
                {copiedSql ? <Check className="h-3 w-3 text-[#22C55E]" /> : <Copy className="h-3 w-3" />}
                <span>{copiedSql ? "COPIADO!" : "COPIAR SQL"}</span>
              </button>
            </div>
          </div>
        )}

        {/* Lista Arcade de Pontuações */}
        <div className="flex-1 overflow-y-auto py-2 space-y-2 pr-1">
          {leaderboard.length === 0 ? (
            <div className="py-12 text-center font-pixel text-xs text-slate-400">
              NENHUM SCORE REGISTRADO AINDA.
            </div>
          ) : (
            leaderboard.map((item, index) => {
              const isTop3 = index < 3;
              const medals = ['🥇', '🥈', '🥉'];

              let cardBg = "bg-white border-black/80 dark:bg-[#16161A]";
              if (index === 0) cardBg = "bg-[#FFFDE7] border-black dark:bg-[#FFE600]/10";
              else if (index === 1) cardBg = "bg-[#F0FDF4] border-black dark:bg-[#00DFD8]/10";
              else if (index === 2) cardBg = "bg-[#FDF2F8] border-black dark:bg-[#FF0080]/10";

              return (
                <div
                  key={item.id}
                  className={`flex items-center justify-between rounded-xl border-2 p-3 shadow-neo-sm ${cardBg}`}
                >
                  <div className="flex items-center gap-3">
                    <span className="flex h-8 w-8 items-center justify-center font-pixel text-xs font-bold">
                      {isTop3 ? medals[index] : `#${index + 1}`}
                    </span>
                    <div>
                      <p className="font-pixel text-xs font-bold text-black dark:text-white uppercase">
                        {item.name}
                      </p>
                      <div className="flex items-center gap-3 text-[11px] font-semibold text-slate-500 dark:text-slate-400 font-sans">
                        <span className="flex items-center gap-1">
                          <Target className="h-3 w-3 text-[#22C55E]" />
                          {item.accuracy}% acurácia
                        </span>
                        <span className="flex items-center gap-1">
                          <Clock className="h-3 w-3 text-slate-400" />
                          {item.totalTime}s
                        </span>
                      </div>
                    </div>
                  </div>

                  <div className="text-right">
                    <span className="font-pixel text-sm font-bold text-black dark:text-[#FFE600]">
                      {item.score} XP
                    </span>
                    <span className="block font-mono text-[9px] text-slate-400">
                      {item.date}
                    </span>
                  </div>
                </div>
              );
            })
          )}
        </div>

        {/* Rodapé do Placar */}
        <div className="flex items-center justify-between border-t-2 border-black/10 pt-4 dark:border-white/10 text-xs">
          <button
            onClick={onClearLeaderboard}
            className="flex items-center gap-1.5 font-pixel text-[9px] text-slate-500 hover:text-[#FF4343] transition uppercase"
          >
            <Trash2 className="h-3 w-3" />
            <span>LIMPAR LOCAL</span>
          </button>
          <button
            onClick={onClose}
            className="neo-btn rounded-xl bg-[#FFE600] px-6 py-2 font-pixel text-xs font-bold text-black uppercase cursor-pointer"
          >
            FECHAR
          </button>
        </div>

      </div>
    </div>
  );
}
