import React, { useState, useEffect } from 'react';
import { 
  Trophy, 
  Clock, 
  Target, 
  X, 
  Trash2, 
  Cloud, 
  Database, 
  Check, 
  RefreshCw, 
  ExternalLink,
  Code,
  Copy
} from 'lucide-react';
import { 
  getStoredSupabaseConfig, 
  saveStoredSupabaseConfig, 
  clearStoredSupabaseConfig, 
  isSupabaseActive 
} from '../utils/supabaseClient';

export default function Leaderboard({ 
  isOpen, 
  onClose, 
  leaderboard, 
  onRefresh, 
  onClearLeaderboard 
}) {
  const [showConfig, setShowConfig] = useState(false);
  const [supabaseUrl, setSupabaseUrl] = useState('');
  const [supabaseKey, setSupabaseKey] = useState('');
  const [configSaved, setConfigSaved] = useState(false);
  const [copiedSql, setCopiedSql] = useState(false);
  const [isRefreshing, setIsRefreshing] = useState(false);

  useEffect(() => {
    if (isOpen) {
      const config = getStoredSupabaseConfig();
      setSupabaseUrl(config.url || '');
      setSupabaseKey(config.anonKey || '');
    }
  }, [isOpen]);

  if (!isOpen) return null;

  const isConnected = isSupabaseActive();

  const handleSaveConfig = (e) => {
    e.preventDefault();
    saveStoredSupabaseConfig(supabaseUrl.trim(), supabaseKey.trim());
    setConfigSaved(true);
    setTimeout(() => setConfigSaved(false), 2500);
    if (onRefresh) onRefresh();
  };

  const handleClearConfig = () => {
    clearStoredSupabaseConfig();
    setSupabaseUrl('');
    setSupabaseKey('');
    if (onRefresh) onRefresh();
  };

  const handleRefreshClick = async () => {
    setIsRefreshing(true);
    if (onRefresh) await onRefresh();
    setTimeout(() => setIsRefreshing(false), 600);
  };

  const sqlScript = `-- 1. Crie a tabela de ranking no SQL Editor do Supabase:
create table public.leaderboard (
  id bigint generated by default as identity primary key,
  name text not null,
  score integer not null,
  accuracy integer not null,
  total_time integer not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Habilite acesso público para o quiz do Provão Paulista:
alter table public.leaderboard enable row level security;
create policy "Permitir leitura pública" on public.leaderboard for select using (true);
create policy "Permitir inserção pública" on public.leaderboard for insert with check (true);`;

  const copySql = () => {
    navigator.clipboard.writeText(sqlScript);
    setCopiedSql(true);
    setTimeout(() => setCopiedSql(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-950/70 p-4 backdrop-blur-sm animate-fadeIn">
      <div className="relative w-full max-w-xl rounded-3xl border border-slate-200 bg-white p-6 shadow-2xl dark:border-slate-800 dark:bg-slate-900 max-h-[92vh] flex flex-col">
        
        {/* Cabeçalho */}
        <div className="flex items-start justify-between border-b border-slate-100 pb-4 dark:border-slate-800">
          <div className="flex items-center gap-3">
            <div className="flex h-11 w-11 items-center justify-center rounded-2xl bg-amber-500/10 text-amber-500 shadow-sm">
              <Trophy className="h-6 w-6" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h2 className="text-lg font-bold text-slate-900 dark:text-white">
                  Placar de Líderes DSA
                </h2>
                {isConnected ? (
                  <span className="inline-flex items-center gap-1 rounded-full bg-emerald-100 px-2.5 py-0.5 text-[10px] font-bold text-emerald-800 dark:bg-emerald-950/80 dark:text-emerald-300">
                    <Cloud className="h-3 w-3 text-emerald-500" />
                    Nuvem (Supabase)
                  </span>
                ) : (
                  <span className="inline-flex items-center gap-1 rounded-full bg-slate-100 px-2.5 py-0.5 text-[10px] font-bold text-slate-600 dark:bg-slate-800 dark:text-slate-300">
                    <Database className="h-3 w-3 text-slate-400" />
                    Local (Navegador)
                  </span>
                )}
              </div>
              <p className="text-xs text-slate-400 mt-0.5">
                {isConnected 
                  ? "Sincronizado em tempo real com o banco de dados Supabase" 
                  : "Salvo no navegador (localStorage). Conecte ao Supabase para ranking compartilhado!"}
              </p>
            </div>
          </div>

          <div className="flex items-center gap-1">
            <button
              onClick={handleRefreshClick}
              disabled={isRefreshing}
              className={`rounded-lg p-2 text-slate-400 hover:bg-slate-100 hover:text-slate-600 dark:hover:bg-slate-800 dark:hover:text-slate-200 transition ${isRefreshing ? 'animate-spin text-brand-600' : ''}`}
              title="Atualizar ranking"
            >
              <RefreshCw className="h-4 w-4" />
            </button>
            <button
              onClick={onClose}
              className="rounded-lg p-2 text-slate-400 hover:bg-slate-100 hover:text-slate-600 dark:hover:bg-slate-800 dark:hover:text-slate-200 transition"
            >
              <X className="h-5 w-5" />
            </button>
          </div>
        </div>

        {/* Botão de Alternância da Configuração do Supabase */}
        <div className="my-2.5 flex items-center justify-between text-xs">
          <span className="text-slate-400">
            {leaderboard.length} pontuações registradas
          </span>
          <button
            onClick={() => setShowConfig(!showConfig)}
            className="flex items-center gap-1 text-xs font-semibold text-brand-600 hover:text-brand-700 dark:text-brand-400 dark:hover:text-brand-300 underline"
          >
            <Database className="h-3.5 w-3.5" />
            <span>{showConfig ? "Ocultar Conexão Supabase" : "⚙️ Conectar / Configurar Supabase"}</span>
          </button>
        </div>

        {/* Painel Expansível de Configuração do Supabase */}
        {showConfig && (
          <div className="mb-3 rounded-2xl border border-brand-200 bg-brand-50/50 p-4 text-xs dark:border-brand-900/60 dark:bg-brand-950/20 animate-fadeIn">
            <div className="flex items-center justify-between mb-2">
              <h3 className="font-bold text-brand-900 dark:text-brand-200 flex items-center gap-1.5">
                <Cloud className="h-4 w-4 text-brand-600 dark:text-brand-400" />
                Integração com Supabase (Requisito 4)
              </h3>
              <a
                href="https://supabase.com"
                target="_blank"
                rel="noreferrer"
                className="text-[11px] flex items-center gap-1 text-brand-600 hover:underline"
              >
                Criar conta grátis <ExternalLink className="h-3 w-3" />
              </a>
            </div>

            <p className="text-slate-600 dark:text-slate-300 mb-3">
              Insira a <strong>URL do Projeto</strong> e a chave <strong>anon/public</strong> do Supabase (disponíveis em <em>Project Settings &gt; API</em>) para que todos os alunos compartilhem o mesmo ranking:
            </p>

            <form onSubmit={handleSaveConfig} className="space-y-2">
              <div>
                <label className="block text-[11px] font-semibold text-slate-700 dark:text-slate-300 mb-1">
                  Project URL:
                </label>
                <input
                  type="url"
                  placeholder="https://xyzcompany.supabase.co"
                  value={supabaseUrl}
                  onChange={(e) => setSupabaseUrl(e.target.value)}
                  className="w-full rounded-lg border border-slate-300 bg-white px-3 py-1.5 text-xs text-slate-800 outline-none focus:ring-2 focus:ring-brand-500 dark:border-slate-700 dark:bg-slate-800 dark:text-slate-100"
                />
              </div>

              <div>
                <label className="block text-[11px] font-semibold text-slate-700 dark:text-slate-300 mb-1">
                  Anon / Public Key:
                </label>
                <input
                  type="password"
                  placeholder="eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9..."
                  value={supabaseKey}
                  onChange={(e) => setSupabaseKey(e.target.value)}
                  className="w-full rounded-lg border border-slate-300 bg-white px-3 py-1.5 text-xs text-slate-800 outline-none focus:ring-2 focus:ring-brand-500 dark:border-slate-700 dark:bg-slate-800 dark:text-slate-100"
                />
              </div>

              <div className="flex items-center gap-2 pt-1">
                <button
                  type="submit"
                  className="rounded-lg bg-brand-600 px-3 py-1.5 font-bold text-white shadow-sm hover:bg-brand-700 active:scale-95 transition"
                >
                  Salvar e Conectar
                </button>
                {isConnected && (
                  <button
                    type="button"
                    onClick={handleClearConfig}
                    className="rounded-lg border border-slate-300 px-3 py-1.5 font-medium text-slate-600 hover:bg-slate-100 dark:border-slate-700 dark:text-slate-300"
                  >
                    Desconectar
                  </button>
                )}
                {configSaved && (
                  <span className="flex items-center gap-1 font-bold text-emerald-600 dark:text-emerald-400">
                    <Check className="h-4 w-4" /> Conectado com sucesso!
                  </span>
                )}
              </div>
            </form>

            {/* Script SQL para a tabela */}
            <div className="mt-3 pt-2.5 border-t border-brand-200/60 dark:border-brand-900/40">
              <div className="flex items-center justify-between mb-1">
                <span className="text-[11px] font-semibold text-slate-600 dark:text-slate-300 flex items-center gap-1">
                  <Code className="h-3 w-3" /> SQL para criar a tabela no Supabase:
                </span>
                <button
                  onClick={copySql}
                  className="flex items-center gap-1 text-[10px] text-brand-600 hover:underline font-bold"
                >
                  {copiedSql ? <Check className="h-3 w-3 text-emerald-500" /> : <Copy className="h-3 w-3" />}
                  <span>{copiedSql ? "Copiado!" : "Copiar SQL"}</span>
                </button>
              </div>
              <pre className="rounded-lg bg-slate-900 p-2 text-[10px] font-mono text-slate-300 overflow-x-auto max-h-24">
                {sqlScript}
              </pre>
            </div>
          </div>
        )}

        {/* Lista de Ranking */}
        <div className="flex-1 overflow-y-auto py-2 space-y-2 pr-1">
          {leaderboard.length === 0 ? (
            <div className="py-12 text-center text-sm text-slate-400">
              Nenhuma pontuação registrada ainda. Complete um quiz para entrar no placar!
            </div>
          ) : (
            leaderboard.map((item, index) => {
              const isTop3 = index < 3;
              const medals = ['🥇', '🥈', '🥉'];

              return (
                <div
                  key={item.id}
                  className={`flex items-center justify-between rounded-2xl border p-3.5 transition ${
                    index === 0
                      ? 'border-amber-300/80 bg-amber-50/50 dark:border-amber-900/50 dark:bg-amber-950/20'
                      : 'border-slate-100 bg-slate-50/60 dark:border-slate-800/80 dark:bg-slate-800/40'
                  }`}
                >
                  <div className="flex items-center gap-3">
                    <span className="flex h-7 w-7 items-center justify-center text-sm font-bold text-slate-500">
                      {isTop3 ? medals[index] : `#${index + 1}`}
                    </span>
                    <div>
                      <p className="text-sm font-bold text-slate-900 dark:text-slate-100">
                        {item.name}
                      </p>
                      <div className="flex items-center gap-3 text-[11px] text-slate-400">
                        <span className="flex items-center gap-1">
                          <Target className="h-3 w-3 text-emerald-500" />
                          {item.accuracy}% acurácia
                        </span>
                        <span className="flex items-center gap-1">
                          <Clock className="h-3 w-3 text-slate-400" />
                          {item.totalTime}s
                        </span>
                      </div>
                    </div>
                  </div>

                  <div className="text-right">
                    <span className="font-mono text-base font-extrabold text-brand-600 dark:text-brand-400">
                      {item.score}
                    </span>
                    <span className="block text-[10px] text-slate-400">
                      {item.date}
                    </span>
                  </div>
                </div>
              );
            })
          )}
        </div>

        {/* Rodapé do Modal */}
        <div className="flex items-center justify-between border-t border-slate-100 pt-4 dark:border-slate-800 text-xs">
          <button
            onClick={onClearLeaderboard}
            className="flex items-center gap-1.5 text-slate-400 hover:text-rose-500 transition"
          >
            <Trash2 className="h-3.5 w-3.5" />
            <span>Limpar Ranking Local</span>
          </button>
          <button
            onClick={onClose}
            className="rounded-xl bg-brand-600 px-5 py-2 font-bold text-white transition hover:bg-brand-700 shadow-sm"
          >
            Fechar
          </button>
        </div>

      </div>
    </div>
  );
}
